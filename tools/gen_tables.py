#!/usr/bin/env python3
"""Generates kernel/dm920eq_tables.h (log2 table, gain table, K-weighting filter)."""
import math, os
out = ['/* generated by tools/gen_tables.py - do not edit */', '#ifndef DM920EQ_TABLES_H', '#define DM920EQ_TABLES_H', '']
log = [round(math.log2(1 + i / 256) * 65536) for i in range(257)]
out.append('/* log2(1 + i/256) in Q16 */')
out.append('static const u32 log2_frac_q16[257] = {' + ', '.join(map(str, log)) + '};')
g = [round(65536 * 10 ** (-i / 200)) for i in range(301)]
out.append('/* 10^(-i/200) in Q16: gain for -0.1*i dB, i = 0..300 (0 .. -30 dB) */')
out.append('static const u32 gain_q16[301] = {' + ', '.join(map(str, g)) + '};')
s1b = [1.53512485958697, -2.69169618940638, 1.19839281085285]; s1a = [-1.69065929318241, 0.73248077421585]
s2b = [1.0, -2.0, 1.0]; s2a = [-1.99004745483398, 0.99007225036621]
q = lambda v: str(int(round(v * (1 << 28))))
out.append('/* K-weighting at 48 kHz, Q28: b0 b1 b2 a1 a2 (y = b.x - a.y) */')
out.append('static const s64 kw1[5] = {' + ', '.join(map(q, s1b + s1a)) + '};')
out.append('static const s64 kw2[5] = {' + ', '.join(map(q, s2b + s2a)) + '};')
out += ['', '#endif', '']
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'kernel', 'dm920eq_tables.h')
open(path, 'w').write('\n'.join(out))
